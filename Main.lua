Lucide.Icons = {}
for name in pairs(registry) do table.insert(Lucide.Icons, name) end
table.sort(Lucide.Icons)
local function getSheet(i)
    if urls[i] then return urls[i] end
    assert(type(getcustomasset) == "function", "Lucide requires custom asset support")
    if not isfolder(folder) then makefolder(folder) end
    local path = folder .. "/" .. i .. ".png"
    if not isfile(path) then
        local data = game:HttpGet(base .. i .. ".png")
        assert(data:sub(1, 8) == "\137PNG\r\n\26\n", "Invalid Lucide PNG: " .. i)
        writefile(path, data)
    end
    urls[i] = getcustomasset(path)
    return urls[i]
end
function Lucide.GetAsset(name)
    local icon = registry[name]
    if not icon then return nil end
    return { IconName = name, Url = getSheet(icon[1]),
        ImageRectSize = Vector2.new(48, 48),
        ImageRectOffset = Vector2.new(icon[2], icon[3]) }
end
return Lucide
